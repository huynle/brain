func buildGoalConfig(args map[string]any) types.GoalConfig {
	cfg := types.GoalConfig{}
	if raw, ok := args["config"].(map[string]any); ok {
		cfg.ID = stringFromMap(raw, "id")
		cfg.Criteria = stringFromMap(raw, "criteria")
		cfg.Validation = stringFromMap(raw, "validation")
		cfg.Workdir = stringFromMap(raw, "workdir")
		cfg.TriggerSource = stringFromMap(raw, "trigger_source")
		cfg.CompleteStatuses = stringSliceFromMap(raw, "complete_statuses")
		cfg.BlockedStatuses = stringSliceFromMap(raw, "blocked_statuses")
	}
	if v := StringArg(args, "goal_id", ""); v != "" {
		cfg.ID = v
	}
	if v := StringArg(args, "criteria", ""); v != "" {
		cfg.Criteria = v
	}
	if v := StringArg(args, "validation", ""); v != "" {
		cfg.Validation = v
	}
	if v := StringArg(args, "workdir", ""); v != "" {
		cfg.Workdir = v
	}
	if v := StringArg(args, "trigger_source", ""); v != "" {
		cfg.TriggerSource = v
	}
	if v := StringSliceArg(args, "complete_statuses"); len(v) > 0 {
		cfg.CompleteStatuses = v
	}
	if v := StringSliceArg(args, "blocked_statuses"); len(v) > 0 {
		cfg.BlockedStatuses = v
	}
	return cfg
}

func buildGoalAction(args map[string]any) types.AutomationAction {
	action := types.AutomationAction{Type: "prompt"}
	if raw, ok := args["action"].(map[string]any); ok {
		action.Type = stringFromMap(raw, "type")
		action.DirectPrompt = stringFromMap(raw, "direct_prompt")
		action.Command = stringFromMap(raw, "command")
		action.Agent = stringFromMap(raw, "agent")
		action.Model = stringFromMap(raw, "model")
		action.Executor = stringFromMap(raw, "executor")
		action.TargetWorkdir = stringFromMap(raw, "target_workdir")
		action.ExecutionMode = stringFromMap(raw, "execution_mode")
		action.SessionMode = stringFromMap(raw, "session_mode")
		action.Timeout = stringFromMap(raw, "timeout")
		action.RequiresCapability = stringFromMap(raw, "requires_capability")
		if b, ok := raw["complete_on_idle"].(bool); ok {
			action.CompleteOnIdle = &b
		}
	}
	if v := StringArg(args, "action_type", ""); v != "" {
		action.Type = v
	}
	if action.Type == "" {
		action.Type = "prompt"
	}
	if v := StringArg(args, "direct_prompt", ""); v != "" {
		action.DirectPrompt = v
	}
	if v := StringArg(args, "command", ""); v != "" {
		action.Command = v
	}
	if v := StringArg(args, "agent", ""); v != "" {
		action.Agent = v
	}
	if v := StringArg(args, "model", ""); v != "" {
		action.Model = v
	}
	if v := StringArg(args, "executor", ""); v != "" {
		action.Executor = v
	}
	if v := StringArg(args, "target_workdir", ""); v != "" {
		action.TargetWorkdir = v
	}
	if v := StringArg(args, "execution_mode", ""); v != "" {
		action.ExecutionMode = v
	}
	if v := StringArg(args, "session_mode", ""); v != "" {
		action.SessionMode = v
	}
	if v := StringArg(args, "timeout", ""); v != "" {
		action.Timeout = v
	}
	if v := StringArg(args, "requires_capability", ""); v != "" {
		action.RequiresCapability = v
	}
	if _, ok := args["complete_on_idle"]; ok {
		b := BoolArg(args, "complete_on_idle", false)
		action.CompleteOnIdle = &b
	}
	return action
}

func buildUpdateGoalRequest(args map[string]any) types.UpdateGoalRequest {
	req := types.UpdateGoalRequest{}
	if v := StringArg(args, "title", ""); v != "" {
		req.Title = &v
	}
	if v := StringArg(args, "content", ""); v != "" {
		req.Content = &v
	}
	if v := StringArg(args, "status", ""); v != "" {
		req.Status = &v
	}
	if v := StringArg(args, "criteria", ""); v != "" {
		req.Criteria = &v
	}
	if v := StringArg(args, "validation", ""); v != "" {
		req.Validation = &v
	}
	if v := StringArg(args, "workdir", ""); v != "" {
		req.Workdir = &v
	}
	if v := StringArg(args, "trigger_source", ""); v != "" {
		req.TriggerSource = &v
	}
	if v := StringSliceArg(args, "complete_statuses"); len(v) > 0 {
		req.CompleteStatuses = &v
	}
	if v := StringSliceArg(args, "blocked_statuses"); len(v) > 0 {
		req.BlockedStatuses = &v
	}
	if hasActionArgs(args) {
		action := buildGoalAction(args)
		req.Action = &action
	}
	return req
}

func hasActionArgs(args map[string]any) bool {
	for _, key := range []string{"action", "action_type", "direct_prompt", "command", "agent", "model", "executor", "target_workdir", "execution_mode", "session_mode", "complete_on_idle", "timeout", "requires_capability"} {
		if _, ok := args[key]; ok {
			return true
		}
	}
	return false
}

func stringFromMap(m map[string]any, key string) string {
	if v, ok := m[key].(string); ok {
		return v
	}
	return ""
}

func stringSliceFromMap(m map[string]any, key string) []string {
	arr, ok := m[key].([]any)
	if !ok {
		return nil
	}
	out := make([]string, 0, len(arr))
	for _, item := range arr {
		if s, ok := item.(string); ok {
			out = append(out, s)
		}
	}
	return out
}

func formatGoalSummary(prefix string, goal *types.GoalSummary) string {
	if goal == nil {
		return prefix
	}
	lines := []string{fmt.Sprintf("%s: %s", prefix, goal.GoalID)}
	if goal.EntryID != "" {
		lines = append(lines, fmt.Sprintf("- entry_id: %s", goal.EntryID))
	}
	if goal.Title != "" {
		lines = append(lines, fmt.Sprintf("- title: %s", goal.Title))
	}
	if goal.Project != "" {
		lines = append(lines, fmt.Sprintf("- project: %s", goal.Project))
	}
	if goal.FeatureID != "" {
		lines = append(lines, fmt.Sprintf("- feature_id: %s", goal.FeatureID))
	}
	if goal.Status != "" {
		lines = append(lines, fmt.Sprintf("- status: %s", goal.Status))
	}
	if goal.Config != nil {
		lines = append(lines, fmt.Sprintf("- trigger_source: %s", goal.Config.NormalizedTriggerSource()))
	}
	return strings.Join(lines, "\n")
}

func formatGoalList(goals []types.GoalSummary) string {
	if len(goals) == 0 {
		return "No goals found.\n\nCreate one with `goal_create`."
	}
	lines := []string{fmt.Sprintf("## Goals (%d)", len(goals)), "", "| goal_id | title | project | feature | status | trigger |", "|---|---|---|---|---|---|"}
	for _, goal := range goals {
		trigger := ""
		if goal.Config != nil {
			trigger = goal.Config.NormalizedTriggerSource()
		}
		feature := goal.FeatureID
		if feature == "" {
			feature = "-"
		}
		project := goal.Project
		if project == "" {
			project = "(global)"
		}
		lines = append(lines, fmt.Sprintf("| %s | %s | %s | %s | %s | %s |", goal.GoalID, goal.Title, project, feature, goal.Status, trigger))
	}
	return strings.Join(lines, "\n")
}

func formatGoalRun(audit *types.GoalReconcileAudit) string {
	if audit == nil {
		return "Reconcile: no audit returned"
	}
	lines := []string{fmt.Sprintf("## Reconcile: %s", audit.GoalID), "", fmt.Sprintf("- Decision: %s", audit.Decision), fmt.Sprintf("- Reason: %s", audit.Reason)}
	if audit.Project != "" {
		lines = append(lines, fmt.Sprintf("- Project: %s", audit.Project))
	}
	if audit.FeatureID != "" {
		lines = append(lines, fmt.Sprintf("- Feature: %s", audit.FeatureID))
	}
	if audit.GeneratedTaskID != "" {
		lines = append(lines, fmt.Sprintf("- Generated task: %s", audit.GeneratedTaskID))
	}
	lines = append(lines, fmt.Sprintf("- Linked tasks: %d", len(audit.LinkedTasks)))
	return strings.Join(lines, "\n")
}

func formatGoalProgress(p *types.GoalProgressResponse) string {
	if p == nil {
		return "Progress: no data returned"
	}
	lines := []string{fmt.Sprintf("## Progress: %s", p.GoalID), ""}
	if p.EntryID != "" {
		lines = append(lines, fmt.Sprintf("- entry_id: %s", p.EntryID))
	}
	if p.Project != "" {
		lines = append(lines, fmt.Sprintf("- Project: %s", p.Project))
	}
	if p.FeatureID != "" {
		lines = append(lines, fmt.Sprintf("- Feature ID: %s", p.FeatureID))
	}
	if p.FeatureStatus != "" {
		lines = append(lines, fmt.Sprintf("- Feature: %s", p.FeatureStatus))
	}
	lines = append(lines, fmt.Sprintf("- Total: %d", p.Total), fmt.Sprintf("- Pending: %d", p.Pending), fmt.Sprintf("- In Progress: %d", p.InProgress), fmt.Sprintf("- Completed: %d", p.Completed), fmt.Sprintf("- Blocked: %d", p.Blocked))
	if len(p.Tasks) > 0 {
		lines = append(lines, "", "### Tasks")
		for _, task := range p.Tasks {
			lines = append(lines, fmt.Sprintf("- %s **%s** (%s)", statusEmojiExtended(task.Status), task.Title, task.ID))
		}
	}
	return strings.Join(lines, "\n")
}

func formatGoalAudit(goalID string, audits []types.GoalReconcileAudit) string {
	if len(audits) == 0 {
		return fmt.Sprintf("No reconcile audit records found for goal %s.", goalID)
	}
	lines := []string{fmt.Sprintf("## Reconcile Audit: %s", goalID), ""}
	for _, audit := range audits {
		lines = append(lines, fmt.Sprintf("- **%s** — %s", audit.Timestamp, audit.Decision))
		if audit.Reason != "" {
			lines = append(lines, fmt.Sprintf("  Reason: %s", audit.Reason))
		}
		if audit.GeneratedTaskID != "" {
			lines = append(lines, fmt.Sprintf("  Generated task: %s", audit.GeneratedTaskID))
		}
		lines = append(lines, fmt.Sprintf("  Linked tasks: %d", len(audit.LinkedTasks)))
	}
	return strings.Join(lines, "\n")
}
