// RegisterGoalTools registers goal automation MCP tools on the server.
func RegisterGoalTools(s *Server, client *APIClient) {
	registerBrainGoalCreate(s, client)
	registerBrainGoalList(s, client)
	registerBrainGoalUpdate(s, client)
	registerBrainGoalLifecycleAlias(s, client, "goal_pause", "Pause a goal automation by setting status to blocked.", "blocked", "Goal paused")
	registerBrainGoalLifecycleAlias(s, client, "goal_resume", "Resume a goal automation by setting status to active.", "active", "Goal resumed")
	registerBrainGoalLifecycleAlias(s, client, "goal_archive", "Archive a goal automation by setting status to archived.", "archived", "Goal archived")
	registerBrainGoalRun(s, client)
	registerBrainGoalProgress(s, client)
	registerBrainGoalAudit(s, client)
}

func goalCommonProperties(includeCreateOnly bool) map[string]Property {
	props := map[string]Property{
		"feature_id":          {Type: "string", Description: "Feature ID to scope the goal"},
		"title":               {Type: "string", Description: "Goal title/objective"},
		"content":             {Type: "string", Description: "Optional goal body/content"},
		"goal_id":             {Type: "string", Description: "Stable goal identifier. Generated by the API if omitted on create."},
		"criteria":            {Type: "string", Description: "Success criteria for the goal"},
		"validation":          {Type: "string", Description: "How goal completion is validated"},
		"workdir":             {Type: "string", Description: "Working directory for generated work"},
		"trigger_source":      {Type: "string", Enum: []string{types.GoalTriggerSourceTask, types.GoalTriggerSourceFeature, types.GoalTriggerSourceBoth}, Description: "Lifecycle events that trigger reconciliation"},
		"complete_statuses":   {Type: "array", Items: &Property{Type: "string"}, Description: "Task statuses that count as complete"},
		"blocked_statuses":    {Type: "array", Items: &Property{Type: "string"}, Description: "Task statuses that count as blocked"},
		"action_type":         {Type: "string", Description: "Automation action type (prompt, script, update, http)"},
		"direct_prompt":       {Type: "string", Description: "Prompt text for prompt actions"},
		"command":             {Type: "string", Description: "Command for script actions"},
		"agent":               {Type: "string", Description: "Agent override"},
		"model":               {Type: "string", Description: "Model override"},
		"executor":            {Type: "string", Description: "Executor override"},
		"target_workdir":      {Type: "string", Description: "Target workdir override"},
		"execution_mode":      {Type: "string", Description: "Execution mode (worktree or current_branch)"},
		"session_mode":        {Type: "string", Description: "Session mode (continue or fresh)"},
		"complete_on_idle":    {Type: "boolean", Description: "Auto-complete generated tasks when the agent goes idle"},
		"timeout":             {Type: "string", Description: "Execution timeout (e.g. 30m, 1h)"},
		"requires_capability": {Type: "string", Description: "Required runner capability"},
		"action":              {Type: "object", Description: "Nested AutomationAction object; flat action_* fields are merged over it"},
	}
	if includeCreateOnly {
		props["project"] = Property{Type: "string", Description: "Project for the goal"}
		props["config"] = Property{Type: "object", Description: "Nested GoalConfig object; flat config fields are merged over it"}
	} else {
		props["status"] = Property{Type: "string", Description: "Goal status"}
	}
	return props
}

func registerBrainGoalCreate(s *Server, client *APIClient) {
	s.RegisterTool(Tool{
		Name:        "goal_create",
		Description: "Create a goal automation: keep working until an objective is satisfied.",
		InputSchema: InputSchema{Type: "object", Properties: goalCommonProperties(true), Required: []string{"project", "title"}},
	}, func(ctx context.Context, args map[string]any) (string, error) {
		project := StringArg(args, "project", "")
		title := StringArg(args, "title", "")
		if project == "" {
			return "", fmt.Errorf("provide a 'project'")
		}
		if title == "" {
			return "", fmt.Errorf("provide a 'title'")
		}

		req := types.CreateGoalRequest{
			Project:   project,
			FeatureID: StringArg(args, "feature_id", ""),
			Title:     title,
			Content:   StringArg(args, "content", ""),
			Config:    buildGoalConfig(args),
			Action:    buildGoalAction(args),
		}

		var goal types.GoalSummary
		if err := client.Request(ctx, http.MethodPost, "/goals", req, nil, &goal); err != nil {
			return "", err
		}
		return formatGoalSummary("Goal created", &goal), nil
	})
}

func registerBrainGoalList(s *Server, client *APIClient) {
	s.RegisterTool(Tool{
		Name:        "goal_list",
		Description: "List active goal automations, optionally filtered by project and feature_id.",
		InputSchema: InputSchema{Type: "object", Properties: map[string]Property{"project": {Type: "string", Description: "Filter by project"}, "feature_id": {Type: "string", Description: "Filter by feature ID"}}},
	}, func(ctx context.Context, args map[string]any) (string, error) {
		query := map[string]string{}
		if project := StringArg(args, "project", ""); project != "" {
			query["project"] = project
		}
		if featureID := StringArg(args, "feature_id", ""); featureID != "" {
			query["feature_id"] = featureID
		}
		var resp struct {
			Goals []types.GoalSummary `json:"goals"`
		}
		if err := client.Request(ctx, http.MethodGet, "/goals", nil, query, &resp); err != nil {
			return "", err
		}
		return formatGoalList(resp.Goals), nil
	})
}

func registerBrainGoalUpdate(s *Server, client *APIClient) {
	s.RegisterTool(Tool{
		Name:        "goal_update",
		Description: "Update a goal automation's title/content/status/config/action fields.",
		InputSchema: InputSchema{Type: "object", Properties: goalCommonProperties(false), Required: []string{"goal_id"}},
	}, func(ctx context.Context, args map[string]any) (string, error) {
		goalID := StringArg(args, "goal_id", "")
		if goalID == "" {
			return "", fmt.Errorf("provide a 'goal_id'")
		}
		req := buildUpdateGoalRequest(args)
		var goal types.GoalSummary
		if err := client.Request(ctx, http.MethodPatch, "/goals/"+url.PathEscape(goalID), req, nil, &goal); err != nil {
			return "", err
		}
		return formatGoalSummary("Goal updated", &goal), nil
	})
}

